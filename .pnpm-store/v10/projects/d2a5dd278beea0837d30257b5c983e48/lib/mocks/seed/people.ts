const id = (n: number) => `emp_${String(n).padStart(4, "0")}`;

export const seedEmployees: SeedEmployee[] = rows.map(
  ([
    n,
    name,
    designation,
    department,
    location,
    manager,
    joinedOn,
    status,
    type,
    ctc,
  ]) => ({
    id: id(n),
    code: `GTF-${1000 + n}`,
    name,
    designation,
    department,
    location,
    managerId: manager === null ? null : id(manager),
    joinedOn,
    status,
    type,
    annualCtc: Math.round(ctc * 100_000),
  }),
);

