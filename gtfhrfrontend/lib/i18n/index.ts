/** Per-href overrides where one English label means different things. */
const navHiByHref: Record<string, string> = {
  "/me/payslips": "वेतन पर्चियाँ",
};

export function navLabel(lang: Lang, label: string, href?: string): string {
  if (lang === "en") return label;
  return (href && label === "Payslips" ? navHiByHref[href] : undefined) ?? navHi[label] ?? label;
}

export function translateNav<T extends { label: string; href: string; children?: { label: string; href: string }[] }>(lang: Lang, items: T[]): T[] {
  if (lang === "en") return items;
  return items.map((item) => ({
    ...item,
    label: navLabel(lang, item.label, item.href),
    ...(item.children ? { children: item.children.map((child) => ({ ...child, label: navLabel(lang, child.label, child.href) })) } : {}),
  }));
}

